const fs = require("node:fs");
const path = require("node:path");

const root = __dirname;
const paths = {
  action: path.join(root, "data/setup-learning-action-v1.json"),
  complete: path.join(root, "data/setup-learning-complete-v1.json"),
  meta: path.join(root, "data/setup-learning-meta.json"),
  output: path.join(root, "js/setup-learning-model.js")
};

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function validateModel(model, kind) {
  if (!model || model.kind !== kind || !Array.isArray(model.featureNames) || !model.model) {
    throw new Error(`Invalid ${kind} setup model`);
  }
  if (model.featureNames.length !== model.model.dim) {
    throw new Error(`${kind} feature/model dimension mismatch`);
  }
}

function buildSource() {
  const action = readJson(paths.action);
  const complete = readJson(paths.complete);
  const meta = readJson(paths.meta);
  validateModel(action, "action");
  validateModel(complete, "conditional-second");
  if (!(meta.blend >= 0 && meta.blend <= 1)) throw new Error("Invalid setup model blend");
  const generations = { gen0: { meta, action, complete } };
  for (const generation of ["gen1", "gen2"]) {
    const bundle = readJson(path.join(root, `data/setup-learning-${generation}.json`));
    validateModel(bundle.action, "action");
    validateModel(bundle.complete, "conditional-second");
    if (bundle.meta.generation !== generation || !bundle.meta.enabled ||
        !(bundle.meta.blend >= 0 && bundle.meta.blend <= 1)) throw new Error(`Invalid ${generation} metadata`);
    generations[generation] = bundle;
  }
  return "// Generated by build-setup-learning-model.js. Do not edit by hand.\n"
    + "var SETUP_LEARNED_GENERATIONS=" + JSON.stringify(generations) + ";\n"
    + "var SETUP_LEARNED_BUNDLE=SETUP_LEARNED_GENERATIONS.gen0;\n";
}

function writeBundle() {
  const source = buildSource();
  fs.writeFileSync(paths.output, source);
  return source;
}

if (require.main === module) writeBundle();
module.exports = { buildSource, paths };
